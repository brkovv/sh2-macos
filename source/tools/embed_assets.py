"""Embed the launcher's PNGs as portable C rather than ELF assembler directives."""
from pathlib import Path
import sys

source, output = map(Path, sys.argv[1:3])
assets = [('font', 'assets/launcher-serif.png')]
with output.open('w', encoding='ascii', newline='\n') as stream:
    stream.write('/* Generated by tools/embed_assets.py. */\n#pragma once\n#include <stdint.h>\n')
    for name, relative in assets:
        data = (source / relative).read_bytes()
        stream.write(f'_Alignas(16) static const uint8_t {name}_png[] = {{\n')
        for start in range(0, len(data), 16):
            stream.write('    ' + ','.join(f'0x{byte:02x}' for byte in data[start:start+16]) + ',\n')
        stream.write(f'}};\n#define {name}_png_end ({name}_png + sizeof {name}_png)\n')
